export function t(
  key: keyof typeof UI_STRINGS,
  lang: Language = "en",
  params?: Record<string, string | number>,
): string {
  const item = UI_STRINGS[key];
  if (!item) return "";
  let text: string = (item as Record<string, string>)[lang] || item.en || "";
  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      text = text.replace(`{${pKey}}`, String(pVal));
    }
  }
  return text;
}
